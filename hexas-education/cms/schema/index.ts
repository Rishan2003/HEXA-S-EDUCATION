import { defineField, defineType } from 'sanity';

const image = defineField({ name: 'image', type: 'image', options: { hotspot: true }, fields: [
  defineField({ name: 'alt', title: 'Alternative text', type: 'string', validation: r => r.required().max(200) }),
  defineField({ name: 'credit', type: 'string' }),
  defineField({ name: 'rightsConfirmed', type: 'boolean', initialValue: false, validation: r => r.custom(v => v === true || 'Confirm permission to publish this image.') }),
] });
const common = [
  defineField({ name: 'title', type: 'string', validation: r => r.required().max(160) }),
  defineField({ name: 'slug', type: 'slug', options: { source: 'title', maxLength: 96 }, validation: r => r.required() }),
  defineField({ name: 'language', type: 'string', initialValue: 'en', options: { list: ['en', 'bn'] }, validation: r => r.required() }),
  defineField({ name: 'summary', type: 'text', rows: 3, validation: r => r.required().max(600) }),
  defineField({ name: 'body', type: 'text', rows: 12, description: 'Plain-text editorial content; separate paragraphs with blank lines.' }),
  image,
  defineField({ name: 'order', type: 'number', initialValue: 0 }),
  defineField({ name: 'sourceUrl', title: 'Primary verification source', type: 'url', validation: r => r.required().uri({ scheme: ['https'] }) }),
  defineField({ name: 'verificationStatus', type: 'string', initialValue: 'pending', options: { list: [{ title: 'Pending review', value: 'pending' }, { title: 'Verified for publication', value: 'verified' }, { title: 'Withdrawn', value: 'withdrawn' }] }, validation: r => r.required() }),
  defineField({ name: 'verifiedBy', type: 'string', validation: r => r.custom((v, context) => context.document?.verificationStatus !== 'verified' || Boolean(v) || 'Name the approving editor.') }),
  defineField({ name: 'verifiedAt', type: 'datetime', validation: r => r.custom((v, context) => context.document?.verificationStatus !== 'verified' || Boolean(v) || 'Add the verification date.') }),
  defineField({ name: 'evidenceNotes', type: 'text', description: 'Record scope, original evidence and remaining limitations. Internal editorial notes.' }),
];
const branchRef = defineField({ name: 'branch', type: 'reference', to: [{ type: 'branch' }] });
export const schemaTypes = [
  defineType({ name: 'course', title: 'Courses', type: 'document', fields: [...common,
    defineField({ name: 'audience', type: 'text', rows: 2, validation: r => r.max(400) }),
    defineField({ name: 'category', type: 'string', options: { list: ['IELTS preparation', 'English language', 'Digital skills'] }, validation: r => r.required() }),
    defineField({ name: 'branches', type: 'array', of: [{ type: 'reference', to: [{ type: 'branch' }] }], validation: r => r.required().min(1) }),
    defineField({ name: 'learningOutcomes', type: 'array', of: [{ type: 'string' }] }),
    defineField({ name: 'enrollmentUrl', type: 'url', validation: r => r.uri({ scheme: ['https'] }) }),
  ] }),
  defineType({ name: 'branch', title: 'Branches', type: 'document', fields: [...common,
    defineField({ name: 'city', type: 'string', validation: r => r.required() }),
    defineField({ name: 'note', type: 'text', description: 'Public visitor guidance; do not add internal notes here.' }),
    defineField({ name: 'active', type: 'boolean', initialValue: true }),
    defineField({ name: 'address', type: 'text', validation: r => r.required() }),
    defineField({ name: 'testVenueAddress', type: 'text', description: 'Separate from the admissions office when floors differ.' }),
    defineField({ name: 'phone', type: 'string' }), defineField({ name: 'email', type: 'string' }),
    defineField({ name: 'location', type: 'geopoint' }),
    defineField({ name: 'mapUrl', type: 'url', validation: r => r.uri({ scheme: ['https'] }) }),
    defineField({ name: 'website', type: 'url', validation: r => r.uri({ scheme: ['https'] }) }),
    defineField({ name: 'facilities', type: 'array', of: [{ type: 'string' }] }),
  ] }),
  defineType({ name: 'achievement', title: 'Achievements', type: 'document', fields: [...common,
    defineField({ name: 'date', type: 'date', description: 'Only enter an exact date if known; otherwise use year.' }),
    defineField({ name: 'year', type: 'number', validation: r => r.integer().min(2007).max(2100) }),
    defineField({ name: 'category', type: 'string', options: { list: ['National', 'International', 'Institutional'] } }),
    defineField({ name: 'issuer', type: 'string', validation: r => r.required() }),
    defineField({ name: 'scope', type: 'string', options: { list: ['organization', 'branch'] }, validation: r => r.required() }),
    { ...branchRef, validation: r => r.custom((v, context) => context.document?.scope !== 'branch' || Boolean(v) || 'Select the recipient branch.') },
  ] }),
  defineType({ name: 'news', title: 'News and announcements', type: 'document', fields: [...common,
    defineField({ name: 'publishedAt', type: 'datetime', validation: r => r.required() }),
    defineField({ name: 'category', type: 'string', options: { list: ['News', 'Event', 'Announcement', 'Learning'] } }), branchRef,
  ] }),
  defineType({ name: 'gallery', title: 'Galleries', type: 'document', fields: [...common, branchRef,
    defineField({ name: 'category', type: 'string', options: { list: ['Recognition', 'Community', 'Learning', 'Events'] } }),
    defineField({ name: 'photos', type: 'array', of: [{ ...image, name: 'photo' }], validation: r => r.min(1) }),
    defineField({ name: 'videoUrl', type: 'url', validation: r => r.uri({ scheme: ['https'] }) }),
  ] }),
  defineType({ name: 'studentStory', title: 'Student stories', type: 'document', fields: [...common, branchRef,
    defineField({ name: 'studentName', type: 'string', validation: r => r.required() }),
    defineField({ name: 'band', type: 'number', validation: r => r.min(0).max(9).precision(1) }),
    defineField({ name: 'consentConfirmed', type: 'boolean', initialValue: false, validation: r => r.custom(v => v === true || 'Obtain explicit student/guardian publishing consent.') }),
    defineField({ name: 'resultVerified', type: 'boolean', initialValue: false, validation: r => r.custom(v => v === true || 'Verify the original result before publishing.') }),
  ] }),
];
